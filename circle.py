import math


def area(r):
    '''
    Calculating circle's area function.
        ARGUMENTS:
            * r (int) - circle's radius
        RETURNS:
            * result area
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Calculating circle's perimeter function.
        ARGUMENTS:
            * r (int) - circle's radius
        RETURNS:
            * result perimeter
    '''
    return 2 * math.pi * r

