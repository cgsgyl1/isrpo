
def area(a, h):
    '''
    Calculating triangle's area function.
        ARGUMENTS:
            * a (int) - triangle's one side's lenght
            * h (int) - triangle's height to this side
        RETURNS:
            * result area
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
    Calculating triangle's perimeter function.
        ARGUMENTS:
            * a (int) - triangle's first side's lenght
            * b (int) - triangle's second side's lenght
            * c (int) - triangle's third side's lenght
        RETURNS:
            * result perimeter
    '''
    return a + b + c
