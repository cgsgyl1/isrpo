
def area(a, b):
    '''
    Calculating rectangle's square function.
        ARGUMENTS:
            * a (int) - rectangle's height
            * b (int) - rectangle's width
        RETURNS:
            * result square
    '''
    return a * b


def perimeter(a, b):
    '''
    Calculating rectangle's perimeter function.
        ARGUMENTS:
            * a (int) - rectangle's height
            * b (int) - rectangle's width
        RETURNS:
            * result perimeter
    '''
    return 2 * (a + b)
